"""Generate the expert and output graphs used by the paged Qwen3.5 runtime."""

from pathlib import Path
import os
import subprocess
import sys


def run_exporter(module, *arguments):
    """Run an isolated exporter without mutating the caller's argument list."""
    environment = os.environ.copy()
    environment["PYTHONPATH"] = os.pathsep.join(
        [str(Path(__file__).resolve().parents[2]), environment.get("PYTHONPATH", "")]
    )
    subprocess.run(
        [sys.executable, "-m", f"models.qwen3_5.{module}", *map(str, arguments)],
        check=True, env=environment,
    )


def export_auxiliary_graphs(output_dir):
    """Return all 13 non-resident graph paths, keyed by runtime-relative stem.

    The two dynamic resident graphs also contain checkpoint weights and are
    generated by export_resident_layer. These graphs take weights as inputs.
    """
    output_dir = Path(output_dir)
    graphs = {}

    def export(module, stem, *arguments):
        path = output_dir / f"{stem}.onnx"
        path.parent.mkdir(parents=True, exist_ok=True)
        run_exporter(module, "--output", path, *arguments)
        graphs[stem] = path

    for sequence in (1, 8, 64):
        for stage in ("gate-up", "down"):
            stem = f"expert/qwen35_moe_{stage.replace('-', '_')}_s{sequence}"
            export("export_expert_stage_onnx", stem, "--stage", stage, "--tokens", sequence)
    for sequence in (1, 64):
        for stage in ("gate-up", "down"):
            stem = f"expert_s16s4/qwen35_moe_s16s4_{stage.replace('-', '_')}_s{sequence}"
            export("export_s16s4_expert_stage_onnx", stem, "--stage", stage, "--tokens", sequence)
    export(
        "export_packed_indexed_grouped_top8_onnx",
        "expert_s16s4/qwen35_moe_s16s4_grouped_top8_packed32_s1",
        "--cache-slots", 32,
    )
    export("export_lm_head_onnx", "lm_head/final_norm", "--kind", "norm")
    export("export_lm_head_onnx", "lm_head/lm_head_62080", "--kind", "lm-head", "--tile-rows", 62080)
    return graphs
